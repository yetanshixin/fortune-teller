def _build_index():
    """构建 (下卦,上卦) → 卦序索引，以及卦名 → 卦序。"""
    idx = {}
    by_name = {}
    for i, (name, lower, upper, guaci, daxiang) in enumerate(_HEXAGRAMS, start=1):
        idx[(lower, upper)] = i
        by_name[name] = i
    return idx, by_name


HEXAGRAM_INDEX, HEXAGRAM_BY_NAME = _build_index()


def hexagram_from_lines(lines):
    """由六爻(自下而上 0/1)得到卦信息。lines: 长度6的 0/1 序列，lines[0]=初爻。"""
    lower = 0
    upper = 0
    for i, y in enumerate(lines[:6]):
        if i < 3:
            lower |= (int(y) & 1) << i
        else:
            upper |= (int(y) & 1) << (i - 3)
    lower_name = TRIGRAM_BY_BINARY[lower]
    upper_name = TRIGRAM_BY_BINARY[upper]
    seq = HEXAGRAM_INDEX[(lower_name, upper_name)]
    name, l, u, guaci, daxiang = _HEXAGRAMS[seq - 1]
    return {
        "seq": seq,
        "name": name,
        "full_name": _full_name(l, u),
        "lower": lower_name,
        "upper": upper_name,
        "guaci": guaci,
        "daxiang": daxiang,
        "binary": (upper << 3) | lower,
    }


def _full_name(lower, upper):
    if lower == upper:
        return {"乾": "乾为天", "坤": "坤为地", "坎": "坎为水", "离": "离为火",
                "震": "震为雷", "艮": "艮为山", "巽": "巽为风", "兑": "兑为泽"}[lower]
    return TRIGRAMS[upper]["image"] + TRIGRAMS[lower]["image"] + _HEXAGRAMS[HEXAGRAM_INDEX[(lower, upper)] - 1][0]


def gong_of_hexagram(seq):
    """返回卦所属的 (宫名, 宫五行, 世爻位, 应爻位, 第几卦)。"""
    name = _HEXAGRAMS[seq - 1][0]
    for gong_name, (wuxing, names) in GONG.items():
        if name in names:
            pos = names.index(name) + 1
            shi = SHI_YAO_POS[pos]
            ying = (shi + 2) % 6 + 1  # 世+3 折回 1~6
            return gong_name, wuxing, shi, ying, pos
    raise ValueError(f"未找到卦序 {seq} 所属宫")


def najia_of_hexagram(lower, upper):
    """返回六爻纳甲地支列表（自初爻到上爻，共6个）。"""
    inner = NAJIA_ZHIS[lower]["inner"]
    outer = NAJIA_ZHIS[upper]["outer"]
    return inner + outer


def liuqin(zi, gong_wuxing):
    """根据地支五行与本宫五行求六亲。"""
    w = ZHI_WUXING[zi]
    if w == gong_wuxing:
        return "兄弟"
    if SHENG[w] == gong_wuxing:
        return "父母"
    if SHENG[gong_wuxing] == w:
        return "子孙"
    if KE[w] == gong_wuxing:
        return "官鬼"
    if KE[gong_wuxing] == w:
        return "妻财"
    return "兄弟"


def line_name(pos):
    """爻位名称：1~6 → 初/二/三/四/五/上。"""
    return ["初", "二", "三", "四", "五", "上"][pos - 1]

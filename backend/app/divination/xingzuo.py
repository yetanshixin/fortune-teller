def _find_xingzuo(month: int, day: int):
    for item in XINGZUO:
        name, en, xiang, (sm, sd), (em, ed), _, _, _ = item
        if sm > em:  # 跨年（摩羯 12.22-1.19）
            if (month == sm and day >= sd) or (month == em and day <= ed):
                return item
        else:
            if (sm < month < em) or (month == sm and day >= sd) or (month == em and day <= ed):
                return item
    return None


def _get(name):
    return next((x for x in XINGZUO if x[0] == name), None)


def compute_xingzuo(month: int, day: int) -> dict:
    """算太阳星座：按出生月日。"""
    item = _find_xingzuo(month, day)
    if not item:
        raise ValueError("出生日期无效")
    name, en, xiang, _, _, character, color, number = item
    return {"name": name, "english": en, "xiang": xiang, "character": character,
            "lucky_color": color, "lucky_number": number}


def compute_xingzuo_peidui(xz1: str, xz2: str) -> dict:
    """星座配对：按四象相性。"""
    a, b = _get(xz1), _get(xz2)
    if not a or not b:
        raise ValueError("星座名称无效")
    rel = _PEIDUI.get((a[2], b[2]), "一般")
    return {
        "xz1": a[0], "xz2": b[0],
        "xiang1": a[2], "xiang2": b[2],
        "relation": rel,
    }


def compute_xingzuo_yunshi(xz: str) -> dict:
    """星座运势：按星座所属四象给出运势。"""
    item = _get(xz)
    if not item:
        raise ValueError("星座名称无效")
    name, en, xiang, _, _, character, color, number = item
    return {"name": name, "xiang": xiang, "yunshi": _YUNSHI[xiang],
            "lucky_color": color, "lucky_number": number}
